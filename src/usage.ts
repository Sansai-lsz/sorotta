import { GAME_COMMAND, NOTIFY_OPTION, RECRUIT_COMMAND, USAGE_COMMAND } from "./commands.ts";
import { reply } from "./discord.ts";

export const USAGE_TEXT = `🎮 **ゲーム募集bot「そろった」の使い方**

「今夜〇〇やる人？」をボタンで集めて、人数がそろったらお知らせしてくれるbotです。

**▶ 募集する人**
\`/${RECRUIT_COMMAND}\` と打って、ゲームを選ぶだけ。
・時間帯を選ぶ（朝・昼・夜・深夜）→ その時間帯の時刻ボタンが出ます
・「いつでも」を選ぶ → 時間帯ごとに「何時から？」を選べる募集になります
・日付も指定できます（例: \`明日\`、\`11/3\`）。省略すると今日
・\`${NOTIFY_OPTION}:@ロール\` でロールにメンションできます（省略するとゲームに登録したロール）
・募集した人は自動で参加扱いになります

**▶ 参加する人**
募集の投稿についているボタンやメニューで選ぶだけ。
・\`21時〜\` などの時刻（「いつでも」募集ではメニューから選ぶ）→ その時刻から参加
・⚡ 今すぐ → 今から参加できる
・🙆 いつでもOK（「いつでも」募集のみ）→ どの時間でもOK
・今日はパス → 不参加
選び直すと上書きされます（🙆 いつでもOK は押すたびにオン・オフが切り替わります）。

**▶ そろったら**
必要な人数がそろうと、メンバーにメンションでお知らせが来ます。
定員を超えた人は「補欠」として表示されます。

**▶ 締め切り・中止**
募集した人が ⚙ を押すと「締め切る」「中止」が出ます。
時間帯が終わった募集は自動で締め切られます。

**▶ ゲームの登録**
募集できるのは登録済みのゲームだけです。
\`/${GAME_COMMAND} add name:ゲーム名 players:最少人数 max:定員 role:@ロール\`（定員とロールは省略可。ロールは募集のたびにメンションされます）
登録済みの一覧は \`/${GAME_COMMAND} list\`。

この説明は \`/${USAGE_COMMAND}\` でいつでも見られます。`;

export function usageResponse(): Response {
  return reply(USAGE_TEXT, { ephemeral: true });
}
